/* Writes calibration/REPORT.md: every target, the reference value, what the
   model gives, and where the reference comes from. `npm run calibrate` */
const fs=require('fs'),path=require('path'),{execSync}=require('child_process');
const {TARGETS,evaluate,describeExpect}=require('./targets.js');
const REFS=require('./references.js');

let sha='uncommitted';
try{sha=execSync('git rev-parse --short HEAD',{cwd:__dirname,stdio:['ignore','pipe','ignore']}).toString().trim();
  if(execSync('git status --porcelain -- ../src',{cwd:__dirname}).toString().trim())sha+=' + local changes to src/';}catch(e){}

const rows=TARGETS.map(t=>({t,...evaluate(t)}));
const count=(st,ok)=>rows.filter(r=>r.t.status===st&&r.ok===ok).length;
const cell=s=>String(s).replace(/\|/g,'\\|');
const refNum={};Object.keys(REFS).forEach((k,i)=>refNum[k]=i+1);

let md=`# Calibration report

Generated by \`npm run calibrate\` on ${new Date().toISOString().slice(0,10)} from model version \`${sha}\`.
Do not edit by hand. See [CALIBRATION.md](../CALIBRATION.md) for how the model was built and how to read this.

**Calibrated targets:** ${count('calibrated',true)} pass, ${count('calibrated',false)} fail.
**Known gaps:** ${count('gap',false)} still missed${count('gap',true)?`, ${count('gap',true)} now passing (promote them)`:''}.

`;
const groups=[...new Set(TARGETS.map(t=>t.group))];
for(const g of groups){
  md+=`## ${g}\n\n| | Target | Reference | Model | Sources |\n|---|---|---|---|---|\n`;
  for(const r of rows.filter(r=>r.t.group===g)){
    const mark=r.t.status==='gap'?(r.ok?'✅ gap now passes':'⚠️ known gap'):(r.ok?'✅':'❌');
    md+=`| ${mark} | **${r.t.id}** ${cell(r.t.claim)} | ${cell(describeExpect(r.t))} | ${r.value==null?'—':cell(r.t.fmt(r.value))} | ${r.t.sources.map(s=>`[${refNum[s]}]`).join(' ')} |\n`;
  }
  const notes=rows.filter(r=>r.t.group===g&&(r.t.why||r.t.gap));
  if(notes.length){md+='\n';for(const r of notes){
    if(r.t.why)md+=`- **${r.t.id}:** ${r.t.why}\n`;
    if(r.t.gap)md+=`- **${r.t.id} (gap):** ${r.t.gap}\n`;}}
  md+='\n';
}
md+=`## References

Each was checked against PubMed, publisher pages or the AANEM site. *Citation* says whether the reference is real and correctly cited. *Claim* says whether what we use it for was seen in the source: **supported** (in the abstract or text), **partial** (part of it, or only in secondary sources) or **unverified** (not checked against the source, usually a textbook page).

`;
for(const [k,r] of Object.entries(REFS))md+=`${refNum[k]}. ${r.cite} ${r.id}  \n   *Used for:* ${r.used}  \n   *Citation:* ${r.citation} · *Claim:* **${r.claim}**. ${r.note}\n`;

fs.writeFileSync(path.join(__dirname,'REPORT.md'),md);
const fail=count('calibrated',false);
console.log(`Wrote calibration/REPORT.md: ${count('calibrated',true)} pass, ${fail} fail, ${count('gap',false)} known gaps.`);
process.exitCode=fail?1:0;
